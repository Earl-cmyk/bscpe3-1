create table if not exists tasks (
    id bigint generated by default as identity primary key,
    title text not null,
    course text not null,
    description text not null,
    deadline timestamptz not null,
    difficulty text not null default 'Medium' check (difficulty in ('Low', 'Medium', 'High')),
    completed boolean not null default false,
    attachment_name text,
    attachment_path text,
    attachment_type text,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists budget_entries (
    id bigint generated by default as identity primary key,
    title text not null default '',
    type text not null check (type in ('deposit', 'withdraw')),
    amount numeric(12, 2) not null check (amount > 0),
    reason text not null,
    status text not null default 'pending' check (status in ('pending', 'spent', 'cancelled')),
    wallet_id bigint,
    course text,
    contributor_id bigint,
    payer_names text not null default '[]',
    attachment_name text,
    attachment_path text,
    attachment_type text,
    created_at timestamptz not null default now()
);

create table if not exists wallets (
    id bigint generated by default as identity primary key,
    name text not null unique,
    course text,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists contributors (
    id bigint generated by default as identity primary key,
    name text not null unique,
    active boolean not null default true,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);

create table if not exists budget_audit_events (
    id bigint generated by default as identity primary key,
    entry_id bigint references budget_entries(id) on delete set null,
    event_type text not null,
    actor text not null default 'system',
    payload jsonb not null default '{}'::jsonb,
    created_at timestamptz not null default now()
);

