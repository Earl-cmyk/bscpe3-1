-- PostgreSQL/Supabase RAG storage. SQLite creates a text-only equivalent at runtime.
create extension if not exists vector;
create table if not exists note_chunks (
    id bigint generated by default as identity primary key,
    note_id bigint not null references notes(id) on delete cascade,
    chunk_index integer not null,
    content text not null,
    content_hash text not null,
    embedding vector(1536),
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (note_id, chunk_index)
);
create index if not exists idx_note_chunks_note on note_chunks (note_id, chunk_index);
create index if not exists idx_note_chunks_embedding_hnsw on note_chunks using hnsw (embedding vector_cosine_ops) where embedding is not null;

create table if not exists interactive_sources (
    id bigint generated by default as identity primary key,
    source_key text not null unique,
    title text not null,
    course text not null,
    content text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now()
);
create table if not exists interactive_source_chunks (
    id bigint generated by default as identity primary key,
    source_id bigint not null references interactive_sources(id) on delete cascade,
    chunk_index integer not null,
    content text not null,
    content_hash text not null,
    created_at timestamptz not null default now(),
    updated_at timestamptz not null default now(),
    unique (source_id, chunk_index)
);
create index if not exists idx_interactive_source_chunks_source on interactive_source_chunks (source_id, chunk_index);
create table if not exists interactive_examples (
    id bigint generated by default as identity primary key,
    title text not null,
    course text not null,
    content text not null,
    created_at timestamptz not null default now()
);
create index if not exists idx_interactive_examples_course on interactive_examples (course, created_at desc);

